define([
    "jquery",
    "lodash",
    "bootstrap"
], function ($, _) {
    var NAMESPACE = "bootstrap-dialog",
        ZINDEX_BACKDROP = 1050,
        ZINDEX_MODAL = 1055,
        ZINDEX_STEP = 20,
        /** Dialogs currently opened (in the order of opening). */
        openedDialogs = [],
        ModalDialog;

    function isModalEvent (event) {
        return event.namespace === "bs.modal";
    }

    function formatContent (dialog, rawContent) {
        var content = _.isFunction(rawContent) ? rawContent.call(rawContent, dialog) : rawContent;
        if (_.isString(content) && dialog.options.nl2br) {
            content = content.replace(/\r\n/g, "<br />").replace(/[\r\n]/g, "<br />");
        }
        return content;
    }

    function enhanceButton ($button) {
        $button.toggleEnable = function (enable) {
            if (_.isUndefined(enable)) {
                this.prop("disabled", !this.prop("disabled"));
            } else {
                this.prop("disabled", !enable).toggleClass("disabled", !enable);
            }
            return this;
        };
        $button.enable = function () {
            return this.toggleEnable(true);
        };
        $button.disable = function () {
            return this.toggleEnable(false);
        };
        return $button;
    }

    /**
     * Modal dialog compatible with the subset of bootstrap-dialog API used by Wren Security applications.
     * Rendered using Bootstrap modal (via its jQuery interface) with bootstrap-dialog markup and CSS classes.
     *
     * @exports org/forgerock/commons/ui/common/components/ModalDialog
     * @param {Object} options dialog options (deep copied as {@link ModalDialog#options})
     * @param {string} [options.id] dialog element identifier (generated by default)
     * @param {string|jQuery|function} [options.title] dialog title (function is called with the dialog)
     * @param {string|jQuery|function} [options.message] dialog message (function is called with the dialog)
     * @param {string} [options.type] one of TYPE_* constants (defaults to TYPE_PRIMARY)
     * @param {string} [options.size] one of SIZE_* constants (defaults to SIZE_NORMAL)
     * @param {string} [options.cssClass] additional CSS class of the dialog element
     * @param {boolean} [options.closable] whether the dialog can be closed by its close button, Escape key and
     *        clicking outside of the dialog (defaults to true)
     * @param {boolean} [options.animate] whether to animate the dialog (defaults to true)
     * @param {boolean} [options.nl2br] whether to convert new lines in string content to line breaks
     *        (defaults to true)
     * @param {string} [options.description] dialog description (aria-describedby)
     * @param {number} [options.tabindex] tabindex of the dialog element (defaults to -1)
     * @param {Object} [options.data] custom data accessible via {@link ModalDialog#getData}
     * @param {Object[]} [options.buttons] buttons with id, label, cssClass, icon, hotkey and action(dialog)
     * @param {function} [options.onshow] called before the dialog is shown, returning false cancels it
     * @param {function} [options.onshown] called after the dialog is shown
     * @param {function} [options.onhide] called before the dialog is hidden, returning false cancels it
     * @param {function} [options.onhidden] called after the dialog is hidden (and removed from the page)
     * @constructor
     */
    ModalDialog = function (options) {
        this.options = $.extend(true, {
            id: _.uniqueId("wrensec-dialog-"),
            type: ModalDialog.TYPE_PRIMARY,
            size: ModalDialog.SIZE_NORMAL,
            cssClass: "",
            title: null,
            message: null,
            closable: true,
            animate: true,
            nl2br: true,
            description: "",
            tabindex: -1,
            data: {},
            buttons: [],
            onshow: null,
            onshown: null,
            onhide: null,
            onhidden: null
        }, options);
        this.indexedButtons = {};
        this.registeredButtonHotkeys = {};
        this.realized = false;
        this.opened = false;
        this.shown = false;
    };

    ModalDialog.NAMESPACE = NAMESPACE;
    ModalDialog.TYPE_DEFAULT = "type-default";
    ModalDialog.TYPE_INFO = "type-info";
    ModalDialog.TYPE_PRIMARY = "type-primary";
    ModalDialog.TYPE_SUCCESS = "type-success";
    ModalDialog.TYPE_WARNING = "type-warning";
    ModalDialog.TYPE_DANGER = "type-danger";
    ModalDialog.SIZE_NORMAL = "size-normal";
    ModalDialog.SIZE_SMALL = "size-small";
    ModalDialog.SIZE_WIDE = "size-wide";
    ModalDialog.SIZE_LARGE = "size-large";

    /** Title used when no title is specified. */
    ModalDialog.DEFAULT_TITLES = {
        "type-default": "Information",
        "type-info": "Information",
        "type-primary": "Information",
        "type-success": "Success",
        "type-warning": "Warning",
        "type-danger": "Danger"
    };

    /**
     * Create and open a dialog.
     * @param {Object} options dialog options
     * @returns {ModalDialog} opened dialog
     */
    ModalDialog.show = function (options) {
        return new ModalDialog(options).open();
    };

    ModalDialog.prototype = {
        constructor: ModalDialog,

        /**
         * Create dialog elements. Called automatically when the dialog is opened for the first time.
         * @returns {ModalDialog} this dialog
         */
        realize: function () {
            var options = this.options,
                id = options.id,
                title = options.title !== null
                    ? formatContent(this, options.title)
                    : ModalDialog.DEFAULT_TITLES[options.type];

            this.$modal = $('<div class="modal" role="dialog" aria-hidden="true"></div>')
                .attr({ "id": id, "aria-labelledby": id + "_title", "tabindex": options.tabindex })
                .addClass([NAMESPACE, options.type, options.size, options.cssClass].join(" "))
                .toggleClass("fade", options.animate);
            if (options.description) {
                this.$modal.attr("aria-describedby", options.description);
            }
            this.$modalDialog = $('<div class="modal-dialog"></div>')
                .toggleClass("modal-sm", options.size === ModalDialog.SIZE_SMALL)
                .toggleClass("modal-lg", options.size === ModalDialog.SIZE_WIDE);
            this.$modalContent = $('<div class="modal-content"></div>');
            this.$modalHeader = $('<div class="modal-header"></div>');
            this.$modalBody = $('<div class="modal-body"></div>');
            this.$modalFooter = $('<div class="modal-footer"></div>');

            this.$modal.append(this.$modalDialog.append(this.$modalContent.append(
                this.$modalHeader, this.$modalBody, this.$modalFooter)));

            this.$modalHeader.append($("<div></div>").addClass(NAMESPACE + "-header").append(
                this.createCloseButton(),
                $("<div></div>").addClass(NAMESPACE + "-title").attr("id", id + "_title").append(title)
            ));
            this.$modalBody.append($("<div></div>").addClass(NAMESPACE + "-body").append(
                $("<div></div>").addClass(NAMESPACE + "-message").append(formatContent(this, options.message))
            ));
            this.$modalFooter.append($("<div></div>").addClass(NAMESPACE + "-footer").append(this.createButtons()));
            this.$modalFooter.toggle(options.buttons.length > 0);

            // Bootstrap closes the dialog by Escape key and by clicking outside of it, unless it is not closable
            this.$modal.modal({ backdrop: options.closable ? true : "static", keyboard: options.closable });
            this.handleModalEvents();
            this.realized = true;
            return this;
        },

        createCloseButton: function () {
            var $button = $('<button type="button" class="btn-close"></button>')
                .attr("aria-label", $.t("common.form.close"));
            return $("<div></div>").addClass(NAMESPACE + "-close-button")
                .append($button)
                .toggle(this.options.closable)
                .on("click", _.bind(this.close, this));
        },

        createButtons: function () {
            var dialog = this,
                $container;
            if (_.isEmpty(this.options.buttons)) {
                return null;
            }
            $container = $("<div></div>").addClass(NAMESPACE + "-footer-buttons");
            _.each(this.options.buttons, function (button) {
                var $button = dialog.createButton(button);
                dialog.indexedButtons[button.id] = $button;
                $container.append($button);
            });
            return $container;
        },

        createButton: function (button) {
            var dialog = this,
                $button = $('<button type="button" class="btn"></button>');
            if (!button.id) {
                button.id = _.uniqueId("wrensec-dialog-button-");
            }
            $button.prop("id", button.id).data("button", button);
            if (_.isString(button.icon) && button.icon.trim() !== "") {
                $button.append($("<span></span>").addClass(NAMESPACE + "-button-icon " + button.icon));
            }
            if (!_.isUndefined(button.label)) {
                $button.append(button.label);
            }
            $button.addClass(_.isString(button.cssClass) && button.cssClass.trim() !== ""
                ? button.cssClass
                : "btn-outline-primary");
            if (this.options.size === ModalDialog.SIZE_LARGE && !/\bbtn-(lg|sm|xs)\b/.test($button.attr("class"))) {
                $button.addClass("btn-lg");
            }
            if (!_.isUndefined(button.hotkey)) {
                this.registeredButtonHotkeys[button.hotkey] = $button;
            }
            $button.on("click", function (event) {
                if (_.isFunction(button.action)) {
                    button.action.call($button, dialog, event);
                }
            });
            return enhanceButton($button);
        },

        handleModalEvents: function () {
            var dialog = this;
            this.$modal.on("show.bs.modal", function (event) {
                var result;
                if (!isModalEvent(event)) {
                    return undefined;
                }
                dialog.opened = true;
                if (_.isFunction(dialog.options.onshow)) {
                    result = dialog.options.onshow(dialog);
                    if (result === false) {
                        dialog.opened = false;
                        _.pull(openedDialogs, dialog);
                    }
                }
                return result;
            });
            this.$modal.on("shown.bs.modal", function (event) {
                if (!isModalEvent(event)) {
                    return;
                }
                dialog.shown = true;
                if (openedDialogs.length > 1) {
                    // Focus trap of the previous dialog moved the focus while this dialog was being shown
                    dialog.$modal.trigger("focus");
                }
                if (_.isFunction(dialog.options.onshown)) {
                    dialog.options.onshown(dialog);
                }
                if (dialog.closeRequested) {
                    dialog.closeRequested = false;
                    dialog.close();
                }
            });
            this.$modal.on("hide.bs.modal", function (event) {
                var result;
                if (!isModalEvent(event)) {
                    return undefined;
                }
                dialog.opened = false;
                if (_.isFunction(dialog.options.onhide)) {
                    result = dialog.options.onhide(dialog);
                    if (result === false) {
                        dialog.opened = true;
                    }
                }
                return result;
            });
            this.$modal.on("hidden.bs.modal", function (event) {
                var lastDialog;
                if (!isModalEvent(event)) {
                    return;
                }
                dialog.shown = false;
                if (_.isFunction(dialog.options.onhidden)) {
                    dialog.options.onhidden(dialog);
                }
                _.pull(openedDialogs, dialog);
                dialog.$modal.modal("dispose").remove();
                // Bootstrap resets the page state when any modal is hidden, restore it for the remaining dialogs
                lastDialog = _.last(openedDialogs);
                if (lastDialog) {
                    $(document.body).addClass("modal-open");
                    lastDialog.$modal.trigger("focus");
                }
            });
            // Not closable dialogs are not animated when closing is attempted (Bootstrap would animate them and its
            // pending animation callbacks would fail if the dialog was closed and disposed in the meantime)
            this.$modal.on("hidePrevented.bs.modal", function (event) {
                return !isModalEvent(event);
            });
            this.$modal.on("keyup", function (event) {
                var $button = dialog.registeredButtonHotkeys[event.which];
                if ($button && !$button.prop("disabled")) {
                    $button.trigger("focus").trigger("click");
                }
            });
        },

        /**
         * Open the dialog (creating its elements first if needed).
         * @returns {ModalDialog} this dialog
         */
        open: function () {
            var level;
            if (!this.realized) {
                this.realize();
            }
            if (!_.includes(openedDialogs, this)) {
                openedDialogs.push(this);
            }
            this.$modal.modal("show");
            // Stack the dialog (and its backdrop) above the previously opened dialogs
            level = Math.max(_.indexOf(openedDialogs, this), 0);
            this.$modal.css("z-index", ZINDEX_MODAL + level * ZINDEX_STEP);
            $(".modal-backdrop").last().css("z-index", ZINDEX_BACKDROP + level * ZINDEX_STEP);
            return this;
        },

        /**
         * Close the dialog. Closed dialog is removed from the page.
         * @returns {ModalDialog} this dialog
         */
        close: function () {
            if (this.opened && !this.shown) {
                // Bootstrap ignores hiding while the dialog is being shown
                this.closeRequested = true;
            } else if (this.realized) {
                this.$modal.modal("hide");
            }
            return this;
        },

        /**
         * Enable or disable all dialog buttons.
         * @param {boolean} enable whether to enable the buttons
         * @returns {ModalDialog} this dialog
         */
        enableButtons: function (enable) {
            _.each(this.indexedButtons, function ($button) {
                $button.toggleEnable(enable);
            });
            return this;
        },

        /**
         * @param {string} id button identifier
         * @returns {jQuery|null} button with additional enable(), disable() and toggleEnable(enable) methods
         */
        getButton: function (id) {
            return _.has(this.indexedButtons, id) ? this.indexedButtons[id] : null;
        },

        getId: function () {
            return this.options.id;
        },

        getTitle: function () {
            return this.options.title;
        },

        getMessage: function () {
            return this.options.message;
        },

        getData: function (key) {
            return this.options.data[key];
        },

        setData: function (key, value) {
            this.options.data[key] = value;
            return this;
        },

        getModal: function () {
            return this.$modal;
        },

        getModalDialog: function () {
            return this.$modalDialog;
        },

        getModalContent: function () {
            return this.$modalContent;
        },

        getModalHeader: function () {
            return this.$modalHeader;
        },

        getModalBody: function () {
            return this.$modalBody;
        },

        getModalFooter: function () {
            return this.$modalFooter;
        },

        isRealized: function () {
            return this.realized;
        },

        isOpened: function () {
            return this.opened;
        }
    };

    return ModalDialog;
});
