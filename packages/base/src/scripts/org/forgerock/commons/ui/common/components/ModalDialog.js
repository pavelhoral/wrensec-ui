define([
    "jquery",
    "lodash",
    "bootstrap"
], function ($, _, bootstrap) {
    var ZINDEX_BACKDROP = 1050,
        ZINDEX_MODAL = 1055,
        ZINDEX_STEP = 20,
        // Bootstrap may still run transition callbacks (e.g. of the static backdrop animation) after a dialog is hidden
        DISPOSE_DELAY = 1000,
        /** Dialogs currently shown (in the order of opening). */
        openedDialogs = [],
        ModalDialog;

    function isModalEvent (event) {
        return event.target === event.currentTarget;
    }

    /**
     * Modal dialog based on Bootstrap 5 modal component.
     *
     * Dialog uses the standard Bootstrap modal markup and triggers the standard Bootstrap modal events
     * (<code>show.bs.modal</code>, <code>shown.bs.modal</code>, <code>hide.bs.modal</code>,
     * <code>hidden.bs.modal</code>, <code>hidePrevented.bs.modal</code>) on its element. Dialogs can be stacked.
     * Dialog is removed from the page when it is hidden and cannot be shown again.
     *
     * @example
     * ModalDialog.show({
     *     title: $.t("common.form.confirm"),
     *     body: $("<p>").text(message),
     *     buttons: [
     *         { label: $.t("common.form.cancel") },
     *         { label: $.t("common.form.delete"), className: "btn-danger", action: (dialog) => remove(dialog) }
     *     ]
     * });
     *
     * @exports org/forgerock/commons/ui/common/components/ModalDialog
     * @param {Object} options dialog options
     * @param {string} [options.id] dialog element identifier (generated by default)
     * @param {string} [options.className] additional CSS classes of the dialog element
     * @param {string|Node|jQuery} [options.title] dialog title (string is text)
     * @param {string|Node|jQuery} [options.body] dialog body (string is HTML)
     * @param {string} [options.variant] theme color of the title (e.g. "danger" for a destructive action)
     * @param {string} [options.size] dialog size: "sm", "lg" or "xl"
     * @param {boolean} [options.scrollable] whether the dialog body scrolls instead of the page (defaults to false)
     * @param {boolean} [options.centered] whether the dialog is vertically centered (defaults to false)
     * @param {boolean} [options.closable] whether the dialog can be dismissed by its close button, Escape key and
     *        clicking outside of it (defaults to true)
     * @param {boolean} [options.animate] whether the dialog is animated (defaults to true)
     * @param {Object[]} [options.buttons] footer buttons (the footer is not rendered without buttons)
     * @param {string} [options.buttons[].id] button element identifier
     * @param {string} options.buttons[].label button label (text)
     * @param {string} [options.buttons[].className] button CSS classes (defaults to "btn-outline-secondary", the
     *        style of buttons dismissing the dialog)
     * @param {boolean} [options.buttons[].disabled] whether the button is initially disabled
     * @param {boolean} [options.buttons[].autofocus] whether the button is focused when the dialog is shown
     * @param {function} [options.buttons[].action] called with the dialog and click event (hides the dialog when not
     *        specified)
     * @constructor
     */
    ModalDialog = function (options) {
        this.options = _.extend({
            id: _.uniqueId("wrensec-modal-"),
            className: "",
            title: "",
            body: null,
            variant: null,
            size: null,
            scrollable: false,
            centered: false,
            closable: true,
            animate: true,
            buttons: []
        }, options);
        this.state = "created";
        this.render();
        this.modal = new bootstrap.Modal(this.element, {
            backdrop: this.options.closable ? true : "static",
            keyboard: this.options.closable
        });
        this.handleEvents();
    };

    /**
     * Create and show a dialog.
     * @param {Object} options dialog options (see {@link ModalDialog})
     * @returns {ModalDialog} the dialog being shown
     */
    ModalDialog.show = function (options) {
        var dialog = new ModalDialog(options);
        dialog.show();
        return dialog;
    };

    /**
     * Show a confirmation dialog with cancel and confirm buttons.
     * @param {Object} options dialog options (see {@link ModalDialog}, body and title can be set, buttons are created,
     *        the variant defaults to "primary")
     * @param {string} [options.confirmLabel] confirm button label (defaults to common.form.ok translation)
     * @param {string} [options.confirmClassName] confirm button CSS classes (defaults to "btn-{variant}" or
     *        "btn-primary")
     * @param {string} [options.cancelLabel] cancel button label (defaults to common.form.cancel translation)
     * @returns {Promise<boolean>} resolved with true when confirmed and false when cancelled or dismissed
     */
    ModalDialog.confirm = function (options) {
        options = _.extend({ variant: "primary" }, options);
        return new Promise(function (resolve) {
            var confirmed = false,
                dialog = new ModalDialog(_.extend(_.omit(options, "confirmLabel", "confirmClassName", "cancelLabel"), {
                    buttons: [{
                        label: options.cancelLabel || $.t("common.form.cancel")
                    }, {
                        label: options.confirmLabel || $.t("common.form.ok"),
                        className: options.confirmClassName ||
                            (options.variant ? "btn-" + options.variant : "btn-primary"),
                        action: function (dialog) {
                            confirmed = true;
                            dialog.hide();
                        }
                    }]
                }));
            dialog.$el.on("hidden.bs.modal", function (event) {
                if (isModalEvent(event)) {
                    resolve(confirmed);
                }
            });
            dialog.show();
        });
    };

    ModalDialog.prototype = {
        constructor: ModalDialog,

        render: function () {
            var options = this.options,
                titleId = options.id + "-title",
                $dialog = $('<div class="modal-dialog"></div>')
                    .toggleClass("modal-" + options.size, !!options.size)
                    .toggleClass("modal-dialog-scrollable", options.scrollable)
                    .toggleClass("modal-dialog-centered", options.centered),
                $header = $('<div class="modal-header"></div>'),
                $title = $('<h1 class="modal-title fs-5"></h1>').attr("id", titleId)
                    .toggleClass("text-" + options.variant, !!options.variant);

            if (_.isString(options.title)) {
                $title.text(options.title);
            } else {
                $title.append(options.title);
            }
            $header.append($title);
            if (options.closable) {
                $header.append($('<button type="button" class="btn-close" data-bs-dismiss="modal"></button>')
                    .attr("aria-label", $.t("common.form.close")));
            }

            this.$body = $('<div class="modal-body"></div>').append(options.body);
            this.$el = $('<div class="modal" tabindex="-1" aria-hidden="true"></div>')
                .attr({ "id": options.id, "aria-labelledby": titleId })
                .addClass(options.className)
                .toggleClass("fade", options.animate)
                .append($dialog.append($('<div class="modal-content"></div>').append(
                    $header, this.$body, this.renderFooter())));
            this.element = this.$el[0];
        },

        renderFooter: function () {
            var dialog = this;
            if (_.isEmpty(this.options.buttons)) {
                return null;
            }
            return $('<div class="modal-footer"></div>').append(_.map(this.options.buttons, function (button) {
                return $('<button type="button" class="btn"></button>')
                    .attr("id", button.id || null)
                    .addClass(button.className || "btn-outline-secondary")
                    .prop("disabled", button.disabled === true)
                    .prop("autofocus", button.autofocus === true)
                    .text(button.label)
                    .on("click", function (event) {
                        if (_.isFunction(button.action)) {
                            button.action.call(this, dialog, event);
                        } else {
                            dialog.hide();
                        }
                    });
            }));
        },

        handleEvents: function () {
            var dialog = this;
            this.$el.on("shown.bs.modal", function (event) {
                if (!isModalEvent(event)) {
                    return;
                }
                dialog.state = "shown";
                if (openedDialogs.length > 1) {
                    // Focus trap of the previous dialog moved the focus while this dialog was being shown
                    dialog.$el.trigger("focus");
                }
                dialog.$el.find("[autofocus]").first().trigger("focus");
                if (dialog.hideRequested) {
                    dialog.hide();
                }
            });
            this.$el.on("hidden.bs.modal", function (event) {
                var lastDialog;
                if (!isModalEvent(event)) {
                    return;
                }
                dialog.state = "hidden";
                _.pull(openedDialogs, dialog);
                // Detached element keeps its data and handlers until the dialog is disposed
                dialog.$el.detach();
                _.delay(function () {
                    dialog.modal.dispose();
                    dialog.$el.remove();
                }, DISPOSE_DELAY);
                // Bootstrap resets the page state when any modal is hidden, restore it for the remaining dialogs
                lastDialog = _.last(openedDialogs);
                if (lastDialog) {
                    $(document.body).addClass("modal-open");
                    lastDialog.$el.trigger("focus");
                }
            });
        },

        /**
         * Show the dialog (stacked on top of other dialogs shown).
         * @returns {Promise<boolean>} resolved with true when the dialog is shown and with false when showing was
         *          prevented by a <code>show.bs.modal</code> event handler
         */
        show: function () {
            var dialog = this,
                showEvent,
                level;
            if (this.state !== "created") {
                return Promise.reject(new Error("Dialog " + this.options.id + " has been already shown"));
            }
            return new Promise(function (resolve) {
                function onShown (event) {
                    if (isModalEvent(event)) {
                        dialog.$el.off("shown.bs.modal", onShown);
                        resolve(true);
                    }
                }
                // Native event is prevented also when a jQuery handler prevents it
                dialog.element.addEventListener("show.bs.modal", function (event) {
                    showEvent = event;
                }, { once: true });
                // Not animated dialog is shown synchronously
                dialog.$el.on("shown.bs.modal", onShown);
                dialog.state = "showing";
                openedDialogs.push(dialog);
                dialog.modal.show();
                if (showEvent && showEvent.defaultPrevented) {
                    dialog.$el.off("shown.bs.modal", onShown);
                    dialog.state = "created";
                    _.pull(openedDialogs, dialog);
                    resolve(false);
                    return;
                }
                // Stack the dialog (and its backdrop) above the previously shown dialogs
                level = Math.max(_.indexOf(openedDialogs, dialog), 0);
                dialog.$el.css("z-index", ZINDEX_MODAL + level * ZINDEX_STEP);
                $(".modal-backdrop").last().css("z-index", ZINDEX_BACKDROP + level * ZINDEX_STEP);
            });
        },

        /**
         * Hide the dialog and remove it from the page.
         * @returns {Promise} resolved when the dialog is hidden
         */
        hide: function () {
            var dialog = this;
            if (this.state === "hidden") {
                return Promise.resolve();
            }
            return new Promise(function (resolve) {
                function onHidden (event) {
                    if (isModalEvent(event)) {
                        dialog.$el.off("hidden.bs.modal", onHidden);
                        resolve();
                    }
                }
                dialog.$el.on("hidden.bs.modal", onHidden);
                if (dialog.state === "showing") {
                    // Bootstrap ignores hiding while the dialog is being shown
                    dialog.hideRequested = true;
                } else if (dialog.state === "shown") {
                    dialog.hideRequested = false;
                    dialog.modal.hide();
                } else {
                    // Dialog has not been shown
                    dialog.$el.off("hidden.bs.modal", onHidden);
                    dialog.state = "hidden";
                    dialog.modal.dispose();
                    resolve();
                }
            });
        },

        /**
         * @param {string} id button identifier
         * @returns {jQuery} footer button with the given identifier
         */
        getButton: function (id) {
            return this.$el.find(".modal-footer > .btn").filter(function () {
                return this.id === id;
            });
        }
    };

    return ModalDialog;
});
